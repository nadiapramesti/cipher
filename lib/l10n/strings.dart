/// Teks UI Cipher dalam dua bahasa. Bahasa aktif diatur lewat [L.lang].
/// Pakai: `tr('kunci')` atau `tr('kunci', {'n': 3})` buat isian `{n}`.
enum AppLang { id, en }

class L {
  static AppLang lang = AppLang.id;
  static bool get isEn => lang == AppLang.en;
  static String get code => lang.name;
}

String tr(String key, [Map<String, Object?> args = const {}]) {
  final table = L.lang == AppLang.en ? _en : _id;
  var s = table[key] ?? _id[key] ?? key;
  args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

